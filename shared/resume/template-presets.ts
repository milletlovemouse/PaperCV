import { DEFAULT_RESUME_STYLE, type Resume, type Template } from "./model";
import { getTemplate, templates, type TemplateCategory } from "./templates";

type TemplateAppearance = Omit<Resume["style"], "paper" | "showPageNumbers">;
export interface TemplatePreset {
  id: string;
  template: Template;
  name: string;
  description: string;
  category: TemplateCategory;
  label: string;
  detail: string;
  defaults: TemplateAppearance;
}
const { paper: _paper, showPageNumbers: _pageNumbers, ...appearanceDefaults } = DEFAULT_RESUME_STYLE;

function preset(
  id: string,
  template: Template,
  name: string,
  description: string,
  label: string,
  detail: string,
  overrides: Partial<TemplateAppearance>,
): TemplatePreset {
  const base = getTemplate(template);
  return {
    id,
    template,
    name,
    description,
    label,
    detail,
    category: base.category,
    defaults: { ...appearanceDefaults, ...base.defaults, ...overrides, template },
  };
}

